"""Hand-written module rows for the four Pakistan demo projects.

The generic seeder derives every register from the bill: its trades, its
firms, its currency. That keeps a project non-empty, but it writes "Project
Owner", "Site Manager" and a tower crane on a ten-marla house. These rows put
the people, letters, risks and site days a Pakistani project team would
actually record on the four projects the PrimeCrest workspace opens with.

Each list has the exact shape ``_generate_module_data`` returns under the same
key; ``DemoTemplate.module_data`` replaces the generated list key by key and
leaves every other register derived. Everyone named here is invented: the
people, the firms, the consultants. Public bodies are named by their role
(the development authority, the water and sanitation agency) because that is
whom a site in that city writes to.

Dates are offsets from the seeder's project start, 1 April 2026, so the same
rows read as a project seven months in: grey structure done on the house,
base course on the road, finishes starting at the school and the health unit.

This file starts with an underscore so the pack loader does not read it as a
template of its own.
"""

