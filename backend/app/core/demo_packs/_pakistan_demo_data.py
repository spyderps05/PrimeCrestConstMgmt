def _field_reports(demo_id: str) -> list[dict]:
    site = _SITE[demo_id]
    rows = []
    days = site["days"]
    for i, (day, trade, work, heads, deliveries, visitors, delay, hours) in enumerate(days):
        moment = _BASE + timedelta(days=day)
        rows.append(
            {
                "report_date": moment.date(),
                "report_type": "daily",
                "weather_condition": site["weather"][moment.month],
                "temperature_c": site["temps"][moment.month],
                "work_performed": work,
                "workforce": [
                    {"trade": trade, "headcount": heads, "hours": "9"},
                    {"trade": "Helpers (mazdoor)", "headcount": max(4, heads // 2), "hours": "9"},
                ],
                "equipment_on_site": list(site["equipment"]),
                "delays": delay,
                "delay_hours": hours,
                "visitors": visitors,
                "deliveries": deliveries,
                # The newest report is still waiting for the engineer's signature.
                "status": "submitted" if i == len(days) - 1 else "approved",
            }
        )
    return rows


def _daily_diary(demo_id: str) -> list[dict]:
    site = _SITE[demo_id]
    rows = []
    for i, (day, trade, work, heads, deliveries, _visitors, delay, hours) in enumerate(site["days"]):
        moment = _BASE + timedelta(days=day + 1)
        cond = site["weather"][moment.month]
        labour = heads + max(4, heads // 2)
        equip = len(site["equipment"])
        notes = f"{labour} workers and {equip} items of plant on site. {trade}: {work}"
        if deliveries:
            notes += f" Received: {deliveries}."
        if delay:
            notes += f" {delay} About {hours:g} hours lost."
        rows.append(
            {
                "diary_date": moment.strftime("%Y-%m-%d"),
                "labour_count": labour,
                "equipment_count": equip,
                "status": "open" if i >= len(site["days"]) - 2 else "closed",
                "notes": notes,
                "weather_summary": {"conditions": cond, "temp_c": int(site["temps"][moment.month])},
            }
        )
    return rows


